//! Build script: generate the element-type table from the `elements.def`
//! snapshot (`native/elmer-mesh/elements.def`, upstream `9f6af2f85`).
//!
//! Each `ELEMENT ... Code NNN ... END ELEMENT` block yields one row:
//! code, dimension, node count, reference node coordinates (U/V/W,
//! missing axes are zero), Gauss-point counts, and the stabilization
//! constant. Edge/face counts follow Elmer's family rule
//! (`ElementBasis.F90`: 2xx->1, 3xx->3, 4xx->4, 5xx->6, 6xx->8, 7xx->9,
//! 8xx->12 edges).

use std::env;
use std::fs;
use std::path::Path;

#[derive(Default)]
struct Elem {
    code: u16,
    dim: u8,
    nodes: usize,
    u: Vec<f64>,
    v: Vec<f64>,
    w: Vec<f64>,
    gauss: Vec<u32>,
    stab: f64,
}

fn main() {
    let dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let raw = fs::read(Path::new(&dir).join("elements.def")).unwrap();
    let text: String = raw.iter().map(|&b| b as char).collect();

    let mut elems: Vec<Elem> = Vec::new();
    let mut cur: Option<Elem> = None;
    for line in text.lines() {
        // `!` ends the line, as in ReadAndTrim.
        let line = match line.find('!') {
            Some(i) => &line[..i],
            None => line,
        };
        let t = line.trim();
        if t.is_empty() {
            continue;
        }
        let low = t.to_lowercase();
        if low.starts_with("element ") {
            cur = Some(Elem::default());
            continue;
        }
        if low == "end element" {
            if let Some(e) = cur.take() {
                if e.code != 0 {
                    elems.push(e);
                }
            }
            continue;
        }
        let e = match cur.as_mut() {
            Some(e) => e,
            None => continue,
        };
        let mut w = t.split_whitespace();
        match w.next().unwrap_or("").to_lowercase().as_str() {
            "dimension" => {
                e.dim = w.next().and_then(|x| x.parse().ok()).unwrap_or(0);
            }
            "code" => {
                e.code = w.next().and_then(|x| x.parse().ok()).unwrap_or(0);
            }
            "nodes" => {
                e.nodes = w.next().and_then(|x| x.parse().ok()).unwrap_or(0);
            }
            "node" => {
                let axis = w.next().unwrap_or("").to_lowercase();
                let vals: Vec<f64> =
                    w.map(|x| x.parse().unwrap_or(0.0)).collect();
                match axis.as_str() {
                    "u" => e.u = vals,
                    "v" => e.v = vals,
                    "w" => e.w = vals,
                    _ => {}
                }
            }
            "gauss" => {
                // `Gauss Points a b c ...`
                w.next(); // "points"
                e.gauss = w.map(|x| x.parse().unwrap_or(0)).collect();
            }
            "stabilization" => {
                e.stab = w.next().and_then(|x| x.parse().ok()).unwrap_or(0.0);
            }
            _ => {}
        }
    }
    elems.sort_by_key(|e| e.code);

    let mut out = String::from(
        "// Generated by build.rs from elements.def. Do not edit.\n\
         #[derive(Debug, Clone, Copy)]\npub struct ElementTypeInfo {\n\
         pub code: u16,\n    pub dim: u8,\n    pub n_nodes: usize,\n\
         pub n_edges: usize,\n    pub stabilization: f64,\n}\n",
    );
    out.push_str(&format!("pub const ELEMENT_TYPES_LEN: usize = {};\n", elems.len()));
    out.push_str("pub const ELEMENT_TYPES: &[ElementTypeInfo] = &[\n");
    for e in &elems {
        let n_edges = match e.code / 100 {
            2 => 1,
            3 => 3,
            4 => 4,
            5 => 6,
            6 => 8,
            7 => 9,
            8 => 12,
            _ => 0,
        };
        out.push_str(&format!(
            "    ElementTypeInfo {{ code: {}, dim: {}, n_nodes: {}, n_edges: {}, stabilization: {:?} }},\n",
            e.code, e.dim, e.nodes, n_edges, e.stab
        ));
    }
    out.push_str("];\n");
    // Reference node coordinates per type, in (U, V, W) triplets.
    out.push_str("pub const ELEMENT_NODES: &[(u16, &[[f64; 3]])] = &[\n");
    for e in &elems {
        out.push_str(&format!("    ({}, &[", e.code));
        for i in 0..e.nodes {
            let (u, v, w) = (
                e.u.get(i).copied().unwrap_or(0.0),
                e.v.get(i).copied().unwrap_or(0.0),
                e.w.get(i).copied().unwrap_or(0.0),
            );
            out.push_str(&format!("[{u:?}, {v:?}, {w:?}], "));
        }
        out.push_str("]),\n");
    }
    out.push_str("];\n");

    let out_dir = env::var("OUT_DIR").unwrap();
    fs::write(Path::new(&out_dir).join("element_table.rs"), out).unwrap();

    println!("cargo:rerun-if-changed=elements.def");
    println!("cargo:rerun-if-changed=build.rs");
}
