//! Build script: compile the vendored MATC C library without any
//! third-party crate (the workspace allowlist has no `cc`, and this keeps
//! the front-end dependency-free), and generate the keyword-type table
//! from the SOLVER.KEYWORDS snapshot.
//!
//! The C compile mirrors `matc/src/CMakeLists.txt`: all 20 sources,
//! include dir `matc/src`, link only `libm`. `str.c` is built `-O0`,
//! exactly as Elmer does for GCC >= 16.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const MATC_SRCS: &[&str] = &[
    "c3d.c", "clip.c", "dri_ps.c", "eig.c", "error.c", "eval.c", "files.c", "funcs.c",
    "gra.c", "gra_com.c", "jacobi.c", "lists.c", "lu.c", "matc.c", "matrix.c", "oper.c",
    "optim.c", "parser.c", "str.c", "urand.c", "variable.c",
];

fn main() {
    let dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());

    build_matc(&dir, &out_dir);
    gen_keywords(&dir, &out_dir);

    println!("cargo:rerun-if-changed=keywords/SOLVER.KEYWORDS");
    println!("cargo:rerun-if-changed=matc/src");
    println!("cargo:rerun-if-changed=matc/config.h");
    println!("cargo:rerun-if-changed=matc/expand_keywords.c");
    println!("cargo:rerun-if-changed=build.rs");
}

fn cc() -> String {
    env::var("CC").unwrap_or_else(|_| "cc".to_string())
}

fn build_matc(dir: &Path, out_dir: &Path) {
    let src_dir = dir.join("matc/src");
    let mut objs = Vec::new();
    for src in MATC_SRCS {
        let obj = out_dir.join(format!("{src}.o"));
        let mut cmd = Command::new(cc());
        if *src == "str.c" {
            // Mirrors matc/src/CMakeLists.txt: str.c miscompiles under
            // GCC >= 16 at optimisation; Elmer forces -O0 there.
            cmd.arg("-O0");
        } else {
            cmd.arg("-O2");
        }
        cmd.arg("-c")
            .arg("-fPIC")
            .arg("-I")
            .arg(&src_dir)
            .arg(src_dir.join(src))
            .arg("-o")
            .arg(&obj);
        let st = cmd.status().expect("C compiler (CC or cc) is required to build matc");
        assert!(st.success(), "compiling matc/{src} failed");
        objs.push(obj);
    }
    let lib = out_dir.join("libmatc.a");
    let st = Command::new("ar")
        .arg("crus")
        .arg(&lib)
        .args(&objs)
        .status()
        .expect("`ar` is required to build matc");
    assert!(st.success(), "archiving libmatc.a failed");
    println!("cargo:rustc-link-search=native={}", out_dir.display());
    println!("cargo:rustc-link-lib=static=matc");
    println!("cargo:rustc-link-lib=m");
}

fn gen_keywords(dir: &Path, out_dir: &Path) {
    let kw_path = dir.join("keywords/SOLVER.KEYWORDS");
    // Latin-1 decode: the snapshot is ASCII except for a latin-1 `!` comment.
    let raw = fs::read(&kw_path).unwrap();
    let text: String = raw.iter().map(|&b| b as char).collect();
    let expanded = expand_dollar_prelude(dir, out_dir, &kw_path);
    let mut entries: Vec<(String, String, String)> = Vec::new();
    // File order; later rows overwrite earlier ones in the map, matching
    // Elmer's HashAdd duplicate policy (firstmate steering 003).
    for line in text.lines().chain(expanded.lines()) {
        // `!` ends the line even inside quotes (ReadAndTrim).
        let line = match line.find('!') {
            Some(i) => &line[..i],
            None => line,
        };
        let line = line.to_lowercase();
        let Some(ci) = line.find(':') else { continue };
        let Some(qi) = line.find('\'') else { continue };
        if qi < ci {
            continue;
        }
        let section = line[..ci].trim().to_string();
        let rest = &line[ci + 1..];
        let Some(cj) = rest.find(':') else { continue };
        let typ = rest[..cj].trim().to_string();
        let after = rest[cj + 1..].trim();
        if !(after.starts_with('\'') && after.ends_with('\'') && after.len() >= 2) {
            continue;
        }
        let keyword = after[1..after.len() - 1].to_string();
        entries.push((section, typ, keyword));
    }

    let mut out = String::from(
        "// Generated by build.rs from keywords/SOLVER.KEYWORDS. Do not edit.\n",
    );
    out.push_str(&format!(
        "pub const KEYWORD_TABLE_LEN: usize = {};\n",
        entries.len()
    ));
    out.push_str("pub const KEYWORD_TABLE: &[(&str, &str, &str)] = &[\n");
    for (section, typ, keyword) in &entries {
        out.push_str(&format!("    ({section:?}, {typ:?}, {keyword:?}),\n"));
    }
    out.push_str("];\n");

    fs::write(out_dir.join("keyword_table.rs"), out).unwrap();
}

/// Evaluate the `$` prelude lines of the snapshot with the vendored
/// libmatc, exactly as ReadAndTrim does when CheckKeyword loads the
/// database. Returns the printed rows (empty when there is no prelude).
fn expand_dollar_prelude(dir: &Path, out_dir: &Path, kw_path: &Path) -> String {
    let probe_c = dir.join("matc/expand_keywords.c");
    let probe = out_dir.join("expand_keywords");
    let lib = out_dir.join("libmatc.a");
    let st = Command::new(cc())
        .arg("-O2")
        .arg("-I")
        .arg(dir.join("matc/src"))
        .arg(&probe_c)
        .arg(&lib)
        .arg("-lm")
        .arg("-o")
        .arg(&probe)
        .status()
        .expect("C compiler (CC or cc) is required to expand SOLVER.KEYWORDS");
    assert!(st.success(), "compiling keyword probe failed");
    let out = Command::new(&probe)
        .arg(kw_path)
        .output()
        .expect("running keyword probe failed");
    assert!(out.status.success(), "expanding SOLVER.KEYWORDS prelude failed");
    String::from_utf8_lossy(&out.stdout).into_owned()
}
